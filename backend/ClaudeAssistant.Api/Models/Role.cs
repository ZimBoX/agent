namespace ClaudeAssistant.Api.Models;

// Управляемый список должностей — источник для выпадающих списков в админке
// (создание сотрудника, привязка шаблона к должности). Не внешний ключ у
// User.Role (та остаётся простой строкой, как и раньше) — это осознанно просто
// "список допустимых значений", чтобы не тащить миграцию существующих данных.
// Template.Roles, наоборот, настоящая связь many-to-many (см. Template.cs) —
// шаблонам нужно точно знать, кому их показывать.
public class Role
{
    public Guid Id { get; set; }
    public required string Name { get; set; }

    // Пользователь с такой должностью видит в клиенте вообще все шаблоны, а не
    // только помеченные под его должность — по запросу пользователя ("хочу
    // чтобы админ имел доступ ко всем шаблонам"), см. TemplatesController.
    public bool IsAdmin { get; set; }

    public DateTimeOffset CreatedAt { get; set; }
}
