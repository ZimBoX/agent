using System.Text.Json;
using Anthropic.Models.Messages;

namespace ClaudeAssistant.Api.Services.AiCompletion;

// Инструмент-справка по инструментам. Общий для основного потока и чата: модель,
// запутавшись (например, крутит create_file по кругу из-за неверной схемы), может
// запросить точную инструкцию и пример вместо серии слепых повторов.
public static class ToolHelp
{
    public static Tool BuildTool() =>
        new()
        {
            Name = "help",
            Description =
                "Справка по инструментам. Если не уверен, как правильно вызвать инструмент (особенно create_file) — "
                + "вызови help с tool=<имя инструмента> и получи точную схему аргументов и пример. Без tool — список всех инструментов. "
                + "Используй это ВМЕСТО повторных неудачных попыток наугад.",
            InputSchema = new()
            {
                Properties = new Dictionary<string, JsonElement>
                {
                    ["tool"] = JsonSerializer.SerializeToElement(
                        new { type = "string", description = "Имя инструмента: create_file, render_page, document_overview, search_document, read_document, list_files, web_search" }
                    ),
                },
                Required = [],
            },
        };

    public static string Text(string? tool)
    {
        var key = (tool ?? "").Trim().ToLowerInvariant();
        return key switch
        {
            "create_file" =>
                "create_file — создаёт файл и прикладывает к ответу.\n"
                + "Аргументы: format (\"xlsx\" или \"docx\"), filename (без расширения).\n"
                + "• Для xlsx добавь sheets — МАССИВ листов, каждый лист {\"name\": <строка, необяз.>, \"rows\": [[...ячейки...], ...]}. "
                + "Первая строка каждого листа — заголовки столбцов. Ячейки — строки или числа. sheets и rows передавай именно как JSON-массивы (НЕ строкой с JSON внутри).\n"
                + "• Для docx передай markdown (заголовки #/##/###, списки \"- \"/\"1. \", таблицы |...|, **жирный**, *курсив*).\n"
                + "Пример xlsx:\n"
                + "{\"format\":\"xlsx\",\"filename\":\"Ведомость объёмов\",\"sheets\":[{\"name\":\"Объёмы\",\"rows\":[[\"Наименование\",\"Ед.\",\"Кол-во\"],[\"Свая С70.30\",\"шт\",\"357\"],[\"Бетон B25\",\"м3\",\"42.5\"]]}]}\n"
                + "Пример docx:\n"
                + "{\"format\":\"docx\",\"filename\":\"Пояснительная записка\",\"markdown\":\"# Заголовок\\n\\nТекст абзаца.\\n\\n- пункт 1\\n- пункт 2\"}\n"
                + "После успеха инструмент вернёт подтверждение — просто кратко скажи пользователю, что файл готов.",
            "render_page" =>
                "render_page — рендерит лист PDF или его РЕГИОН в картинку.\n"
                + "Аргументы: path (относительный путь к PDF), page (номер листа с 1), region (необязательно).\n"
                + "region — доли 0..1 от всего листа, начало в верхнем-левом углу: {\"x\":0.5,\"y\":0.5,\"width\":0.5,\"height\":0.5} = правая нижняя четверть.\n"
                + "Числа читай ТОЛЬКО с вырезки region (не с полного листа). Мелко/размыто — вырежи меньше и повтори.",
            "document_overview" =>
                "document_overview — превью всех листов PDF сеткой с номерами.\n"
                + "Аргументы: path, from (необяз., с какого листа). Найди по превью, где таблицы, дальше открывай их через render_page с region.",
            "search_document" =>
                "search_document — поиск по текстовому слою PDF.\n"
                + "Аргументы: path, query. У сканов текстового слоя нет — там используй document_overview + render_page.",
            "read_document" =>
                "read_document — читает документ (docx/xlsx/pdf) как текст; длинный текст листается через offset. "
                + "Скан без текстового слоя вернётся картинками страниц. Аргументы: path, offset (необяз.).",
            "list_files" =>
                "list_files — список файлов и папок внутри объекта. Аргумент: path (пусто = корень). Рядом с файлом показан его размер.",
            "web_search" =>
                "web_search — поиск в интернете. Вызывается автоматически, когда нужны свежие внешние данные; ограничен по числу вызовов.",
            _ =>
                "Доступные инструменты (вызови help с tool=<имя> за подробностями):\n"
                + "• create_file — сделать файл Excel (xlsx) или Word (docx) и приложить к ответу.\n"
                + "• list_files — список файлов объекта.\n"
                + "• read_document — прочитать документ как текст (или картинки для скана).\n"
                + "• document_overview — превью всех листов PDF, чтобы найти нужные таблицы.\n"
                + "• render_page — отрендерить лист/вырезку PDF для чтения цифр.\n"
                + "• search_document — поиск по текстовому слою PDF.\n"
                + "• web_search — поиск в интернете.",
        };
    }
}
